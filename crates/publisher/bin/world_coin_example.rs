//! # World Coin Block Header Verification Example
//!
//! This example demonstrates how to verify an Ethereum block header using the RISC0 zkVM
//! and extract verified block information.
//!
//! ## Overview
//!
//! This example showcases a complete workflow for verifying Ethereum block header:
//!
//! 1. **API Call (Outside Guest Program)**: The `verify_single_block_header` API endpoint
//!    should be called from outside the guest program. This function:
//!    - Fetches a block header from the database
//!    - Generates a STARK proof of the block header's validity
//!    - Returns a receipt containing the proof and journal data
//!
//! 2. **Receipt Handling (In Guest Program)**: The receipt should be passed as input to
//!    the Risc0 guest program where:
//!    - The receipt is verified using `receipt.verify(WORLD_COIN_ID)`
//!    - This verification ensures the proof was generated by the correct program
//!    - It confirms the cryptographic integrity of the block header data
//!
//! 3. **Journal Extraction (In Guest Program)**: After verification, the Risc0 guest program:
//!    - Extracts the journal data from the receipt
//!    - Decodes it into the `Output` struct containing verified block information
//!    - Can trust this data as cryptographically verified
//!
//! ## Security Considerations
//!
//! This separation of concerns ensures:
//! - The proof generation happens outside the Risc0 guest program (which may have resource constraints)
//! - The verification happens inside the Risc0 guest program (ensuring cryptographic integrity)
//! - The extracted data can be trusted by the Risc0 guest program for further processing
//!
//! ## Usage
//!
//! This example is intended to demonstrate the pattern. In a real application:
//! - The API would be called by an external service
//! - The receipt would be passed to a zkVM guest program
//! - The guest program would verify and use the data for further cryptographic operations
//!
//! The verification provides strong guarantees that the block data is authentic and
//! has not been tampered with.
//!
//! ## Importing as a Dependency
//!
//! To use this functionality in your project, add the following to your `Cargo.toml`:
//!
//! ```toml
//! [dependencies]
//! publisher = { git = "https://github.com/OilerNetwork/fossil-light-client.git", package = "publisher" }
//! guest-types = { git = "https://github.com/OilerNetwork/fossil-light-client.git", package = "guest-types" }
//! methods = { git = "https://github.com/OilerNetwork/fossil-light-client.git", package = "methods" }
//! ```
//!
//! This allows you to integrate Ethereum block header verification with cryptographic
//! guarantees into your own applications.

use eyre::{eyre, Result};
use guest_types::WorldCoinOutput;
use methods::WORLD_COIN_ID;
use publisher::api::operations::verify_single_block_header;
use tracing::info;
use tracing_subscriber::{fmt, prelude::*, EnvFilter};

#[tokio::main]
async fn main() -> Result<()> {
    // Initialize tracing with info level by default
    tracing_subscriber::registry()
        .with(fmt::layer())
        .with(EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")))
        .init();

    let block_number = 7800000;
    let chain_id = 11155111; // Sepolia

    info!("Starting single block header verification example");

    info!(
        "Verifying block header for block {} on chain ID {}",
        block_number, chain_id
    );

    // STEP 1: Call the API to verify the block header and get the receipt
    // NOTE: In a real application, this would happen outside the guest program
    let receipt = verify_single_block_header(block_number, chain_id).await?;

    // STEP 2: Verify the receipt
    // NOTE: In a real application, this would happen inside the guest program
    receipt
        .verify(WORLD_COIN_ID)
        .map_err(|e| eyre!("Failed to verify receipt: {}", e))?;

    // STEP 3: Extract journal data from the receipt
    // NOTE: In a real application, this would happen inside the guest program
    let output: WorldCoinOutput = receipt
        .journal
        .decode()
        .map_err(|e| eyre!("Failed to decode journal output: {}", e))?;

    // Display the extracted information
    info!("Block verification successful!");
    info!("Block Number: {}", output.block_number());
    info!("Block Hash: {}", output.block_hash());
    info!("State Root: {}", output.state_root());

    info!("This data is cryptographically verified and can be trusted by the guest program");

    Ok(())
}
